/* ============================================================================
   tools/make-phl-geo.js — regenerate assets/js/phl-geo.js

   Lifts the pre-projected coastline table out of 3d-map.html (the Natural Earth
   10 m extraction that plate was built from) and writes it as a plain JS asset
   the cockpit can load through pc_asset().

   Run from the project root:   node tools/make-phl-geo.js

   NEVER SHIP tools/ — same rule as make-icons.php. 3d-map.html is the source
   and is likewise not part of the deployed app.
============================================================================ */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, '3d-map.html');
const OUT = path.join(ROOT, 'assets', 'js', 'phl-geo.js');

const html = fs.readFileSync(SRC, 'utf8');
const m = html.match(/<script type="application\/json" id="phl-data">([\s\S]*?)<\/script>/);
if (!m) { console.error('phl-data block not found in 3d-map.html'); process.exit(1); }

const D = JSON.parse(m[1]);

/* Points are already in scene units — x = (lon-lon0)*kx*scale, y = (lat-lat0)*scale
   — and already rounded to 2dp upstream. Nothing to re-project here; this is a
   transcription, not a transform. */
const islands = D.islands.map((i) => ({
  n: i.n || '',
  a: i.a || 0,
  c: i.c,
  p: i.p,
}));

/* One island per line keeps the file diffable; the coordinate arrays stay on
   that line because a point-per-line file would be 3,000 lines of noise. */
const body = islands.map((i) => '  ' + JSON.stringify(i)).join(',\n');

const out = `/* ============================================================================
   phl-geo.js — Philippine coastlines, pre-projected

   GENERATED by tools/make-phl-geo.js from 3d-map.html. Do not hand-edit.

   ${islands.length} landmasses from Natural Earth 10 m, Batan in the north to
   Sibutu off Borneo. Points are plane coordinates, not degrees:

     x = (lon - lon0) * kx * scale        kx corrects longitude for latitude
     y = (lat - lat0) * scale             scale is units per degree

   so one unit is 111.32 / scale km and the origin sits at the centre of the
   archipelago's bounding box. phl-map.js turns these into the relief plate.
============================================================================ */
'use strict';
window.PC_PHL = {
  lon0: ${D.lon0}, lat0: ${D.lat0}, kx: ${D.kx}, scale: ${D.scale},
  bounds: ${JSON.stringify(D.bounds)},
  islands: [
${body}
  ]
};
`;

fs.writeFileSync(OUT, out, 'utf8');

let pts = 0;
islands.forEach((i) => { pts += i.p.length; });
console.log(`wrote ${path.relative(ROOT, OUT)} — ${islands.length} islands, ${pts} points, ` +
            `${(Buffer.byteLength(out) / 1024).toFixed(1)} KB`);
